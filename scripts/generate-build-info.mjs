// scripts/generate-build-info.mjs — generates src/build-info.ts at build/deploy time.
//
// Guarantees that /health and deployment consoles always have a non-null,
// build-time stamped commit identity and working-tree cleanliness status,
// even when runtime RELEASE_SHA env vars are not set.

import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export function generateBuildInfo() {
  let commit = null
  let clean = false
  let ref = null

  try {
    const rawSha = execSync('git rev-parse HEAD', { encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] }).trim()
    if (/^[0-9a-f]{40}$/i.test(rawSha)) {
      commit = rawSha.toLowerCase()
    }
  } catch {
    commit = null
  }

  try {
    const status = execSync('git status --porcelain', { encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] }).trim()
    ref = execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] }).trim()
    clean = status.length === 0
  } catch {
    clean = false
  }

  const targetFile = join(process.cwd(), 'src', 'build-info.ts')
  let existing = null
  try {
    existing = readFileSync(targetFile, 'utf8')
  } catch {
    existing = null
  }

  if (existing) {
    const objectMatch = existing.match(/export const BUILD_INFO:\s*BuildInfo\s*=\s*\{([^}]+)\}/)
    if (objectMatch) {
      const block = objectMatch[1]
      const commitMatch = block.match(/commit:\s*("[^"]+"|\S+),/)
      const cleanMatch = block.match(/clean:\s*(true|false),/)
      const refMatch = block.match(/ref:\s*("[^"]+"|\S+),/)

      const existingCommit = commitMatch ? (commitMatch[1] === 'null' ? null : JSON.parse(commitMatch[1])) : undefined
      const existingClean = cleanMatch ? cleanMatch[1] === 'true' : undefined
      const existingRef = refMatch ? (refMatch[1] === 'null' ? null : JSON.parse(refMatch[1])) : undefined

      if (existingCommit === commit && existingClean === clean && existingRef === ref) {
        return { commit, clean, builtAt: null, ref }
      }
    }
  }

  const builtAt = new Date().toISOString()

  const content = `// Generated build information module — DO NOT EDIT DIRECTLY.
// Generated by scripts/generate-build-info.mjs

export interface BuildInfo {
  commit: string | null
  clean: boolean
  builtAt: string | null
  ref: string | null
}

export const BUILD_INFO: BuildInfo = {
  commit: ${commit ? JSON.stringify(commit) : 'null'},
  clean: ${JSON.stringify(clean)},
  builtAt: ${JSON.stringify(builtAt)},
  ref: ${ref ? JSON.stringify(ref) : 'null'},
}
`

  writeFileSync(targetFile, content, 'utf8')
  return { commit, clean, builtAt, ref }
}

if (process.argv[1] && process.argv[1].endsWith('generate-build-info.mjs')) {
  const result = generateBuildInfo()
  console.log(`[build-info] Stamped commit: ${result.commit ?? 'null'}, clean: ${result.clean}, ref: ${result.ref}, builtAt: ${result.builtAt}`)
}
